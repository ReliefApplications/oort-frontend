// tools/scripts/set-build-version.js
const fs = require('fs');
const path = require('path');

// 1. Get the destination path from the command line arguments
// Example usage: node tools/scripts/set-build-version.js apps/my-app/src/environments/version.ts
const relativePath = process.argv[2];

if (!relativePath) {
  console.error('Error: No version file path provided.');
  process.exit(1);
}

const versionFilePath = path.join(process.cwd(), relativePath);

// 2. Create the timestamp
const now = new Date();
const year = now.getFullYear();
const month = String(now.getMonth() + 1).padStart(2, '0');
const day = String(now.getDate()).padStart(2, '0');
const hour = String(now.getHours()).padStart(2, '0');
const minute = String(now.getMinutes()).padStart(2, '0');

const buildVersion = `${year}${month}${day}${hour}${minute}`;

// 3. Prepare and write the file
const content = `// This file is auto-generated by tools/scripts/set-build-version.js
// Do not edit this file directly.
/** Build version in the format YYYYMMDDHHMM */
export const buildVersion = '${buildVersion}';\n`;

try {
  fs.writeFileSync(versionFilePath, content);
  console.log(`Build version ${buildVersion} written to ${relativePath}`);
} catch (err) {
  console.error(`Error writing version file: ${err.message}`);
  process.exit(1);
}
